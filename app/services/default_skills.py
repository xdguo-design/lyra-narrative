BUILTIN_WRITING_SKILL_CONTENT = """【NarrativeOS 默认写作 Skill：中文小说自然叙事】

目标：写出有叙事味、有人物温度、普通读者能直接进入的中文小说。不要把“短、快、利落”误当成高级感。

一、句式与段落
1. 短句只在需要撞击感、停顿、危险逼近、情绪断裂、关键判断时使用，不得作为默认句式。
2. 普通叙事优先使用自然的中长句，把动作、观察、身体感受、关系变化或潜台词组织在同一个完整语流里。
3. 避免连续三句以上都只有几个字，避免一行一句造成“电报体”“短视频文案体”。
4. 段落应承载一个完整的小动作、小观察或小情绪。除非刻意强调，不要每句话都单独成段。
5. 长短句变化要服从场景呼吸，而不是机械交替。

二、描写必须给读者可感知的东西
1. 优先写“像什么”“具体是什么感觉”“身体或环境发生了什么”，让读者能看见、听见、摸到或联想到经验。
2. 少用单独的排除式描写，例如“不像风，也不像地下水”“不是害怕，也不是紧张”。如果必须使用否定，要紧接一个明确、具体、可感知的正向描述。
3. 比喻必须来自人物当下经验、职业、记忆或场景，不要为了漂亮而比喻。
4. 不用抽象形容词代替现场，例如“诡异、压迫、危险、冰冷”应尽量由声音、温度、距离、动作和人物反应体现。

三、陌生术语第一次出现时必须落地
1. 不默认读者懂行业黑话、学科术语、缩写和系统名。
2. 能用生活化中文说清楚，就不用术语。
3. 必须使用术语时，第一次出现要让含义自然落在上下文里：通过人物动作、用途、结果或一句不露痕迹的解释让读者马上明白。
4. 禁止为了显得专业而堆专业词。专业感来自正确的行为和细节，不来自名词密度。

四、对白必须有人际关系和情绪目的
1. 每句对白至少承担一种人物意图：试探、躲避、攻击、安抚、掩饰、争夺、示弱、逼问、拖延、求证或建立距离。
2. 避免“提问—回答—提问—回答”的资料问答。设定信息要被人物关系、动作和利益打断、扭曲或拒绝。
3. 人物不会为了给读者解释而说话。先问：他为什么此刻愿意说这句话？他说给谁听？想得到什么？
4. 同一句事实，不同人物应该有不同说法。用词、停顿、回避方式、攻击方向要体现性格和关系。
5. 对白之间适量加入动作、视线、呼吸、犹豫、环境反馈，让情绪有落脚点；不要每一句都配动作，也不要完全悬空。

五、克制“模型腔”
以下结构不是禁用，但禁止高频重复：
- “不是A，是B”
- “不是因为A，而是因为B”
- “这三个字……”
- “这一瞬间……”
- “第一次真正……”
- “没有X，没有Y，只有Z”
- 为了制造金句而把完整语义切成多个单行短句
同一章反复出现这些结构时，应主动改写。

六、信息与情感
1. 设定必须附着在人物正在做的事、承担的风险、失去的东西或彼此的冲突上。
2. 读者先感受到人物，再理解规则；先看见后果，再接受解释。
3. 技术细节如果不改变人物选择、不增加风险、不能形成画面，应删减或后移。
4. 情绪不要直接命名完就结束。优先写情绪如何改变动作、声音、注意力、判断或人与人的距离。

七、自检
交稿前逐段检查：
- 是否连续出现过多短句或单句段落？
- 是否有只写“不像什么”却没有写清“像什么”的描写？
- 是否出现读者第一次见就无法理解的术语？
- 对白是否只是传递信息，没有人物目的和关系温度？
- 是否出现明显“模型腔”模板重复？
若任一项成立，先改再交。
"""


